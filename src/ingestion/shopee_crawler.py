"""Shopee product reviews through the public ratings API behind shopee.vn pages.

Status 2026-11-04: Shopee answers the very first request with HTTP 403 and
error 90309999 unless the client has a logged-in session and the request
signatures generated by Shopee's own JavaScript. Product pages are an empty
JavaScript shell, so their HTML holds no reviews either. This module does not
work around that protection: it makes plain requests, raises ShopeeBlockedError
(recorded per job in report.json by src.ingestion.collect) and saves raw
ratings only if Shopee answers with data.

The success path follows the get_ratings format documented publicly before the
block (data.ratings[] with cmtid, comment, rating_star, ctime); it could not be
verified live.
"""
import time

import requests

from src.ingestion.common import envelope, retry

RATINGS_URL = 'https://shopee.vn/api/v2/item/get_ratings'
PAGE_SIZE = 50  # Cannot be verified while the API is blocked.
ANTI_BOT_ERROR = 90309999


class ShopeeBlockedError(RuntimeError):
    """Shopee refused the request with its anti-bot response; never retried."""


def pages(job, cursor, *, delay, attempts, timeout):
    """Yield (raw_events, next_cursor, exhausted) per ratings page from cursor['offset']."""
    shop_id, item_id = job['app_id'].split('.')
    with requests.Session() as session:
        session.headers.update({'User-Agent': 'MultiDomainSentimentResearch/1.0',
                                'Accept': 'application/json'})

        def get(params):
            def request():
                response = session.get(RATINGS_URL, params=params, timeout=timeout)
                try:
                    body = response.json()
                except ValueError:
                    body = None
                if isinstance(body, dict) and body.get('error') == ANTI_BOT_ERROR:
                    raise ShopeeBlockedError(
                        f'Shopee anti-bot block: HTTP {response.status_code}, error {ANTI_BOT_ERROR}, '
                        f'is_login={body.get("is_login")}; no data collected')
                response.raise_for_status()
                if body is None:
                    raise ValueError('Shopee returned a non-JSON response')
                return body
            return retry(request, attempts)

        offset = cursor.get('offset', 0)
        while True:
            time.sleep(delay)
            payload = get({'itemid': item_id, 'shopid': shop_id, 'offset': offset,
                           'limit': PAGE_SIZE, 'type': 0, 'filter': 0, 'flag': 1})
            ratings = parse_page(payload, offset)
            # The product detail API is blocked the same way, so there is no app metadata.
            rows = [envelope('shopee', job['app_id'], job['country'], None, None, rating)
                    for rating in ratings]
            exhausted = len(ratings) < PAGE_SIZE
            yield rows, {'offset': offset + len(ratings)}, exhausted
            if exhausted:
                return
            offset += len(ratings)


def parse_page(payload, offset):
    """Return the raw rating dicts; fail loudly on API errors or an unknown format."""
    error = payload.get('error') if isinstance(payload, dict) else None
    data = payload.get('data') if isinstance(payload, dict) and error in (None, 0) else None
    if isinstance(data, dict):
        ratings = data.get('ratings') or []
        if isinstance(ratings, list) and all(isinstance(row, dict) for row in ratings):
            return ratings
    raise ValueError(f'Unexpected Shopee ratings response at offset {offset} (error={error})')
